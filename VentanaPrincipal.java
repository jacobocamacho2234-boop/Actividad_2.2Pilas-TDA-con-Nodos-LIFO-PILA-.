    //Metodo creado para optimizar el boton push
    private boolean validarCampos() {
    if (txtTitulo.getText().trim().isEmpty()
            || txtAutor.getText().trim().isEmpty()
            || txtIsbn.getText().trim().isEmpty()
            || txtPrecio.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Todos los campos son obligatorios.",
                "Datos incompletos",
                JOptionPane.WARNING_MESSAGE);

        return false;
    }

    return true;
}
    //Metodos Creados para optimizar el boton push
    private double obtenerPrecio() { 
    try {
        double precio = Double.parseDouble(txtPrecio.getText().trim());

        if (precio <= 0) {
            throw new IllegalArgumentException(
                    "El precio debe ser mayor a cero.");
        }

        return precio;

    } catch (NumberFormatException e) {
        throw new IllegalArgumentException(
                "El precio debe ser un número válido.");
    }
}
    //Metodos nuevos
    private void limpiarFormulario() {
    txtTitulo.setText("");
    txtAutor.setText("");
    txtIsbn.setText("");
    txtPrecio.setText("");
    lblPreview.setText("Sin Imagen");
    rutaImagenSeleccionada = "";
}
    private void actualizarVistaPila() {

    pnlContenedor.removeAll();

    if (pilaLibro != null && !pilaLibro.estaVacia()) {

        Nodo actual = pilaLibro.getTope();
        boolean esTope = true;

        while (actual != null) {

            Libros libro = actual.getDato();

            PanelLibroItem panel =
                    new PanelLibroItem(libro, esTope);

            pnlContenedor.add(panel);

            actual = actual.getSiguiente();
            esTope = false;
        }
    }

    pnlContenedor.revalidate();
    pnlContenedor.repaint();
}
