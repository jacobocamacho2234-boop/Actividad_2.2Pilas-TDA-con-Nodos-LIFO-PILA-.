    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed

    JFileChooser selector = new JFileChooser();

    int resultado = selector.showOpenDialog(this);

    if (resultado == JFileChooser.APPROVE_OPTION) {

        File archivo = selector.getSelectedFile();

        rutaImagenSeleccionada = archivo.getAbsolutePath();

        ImageIcon imagen = new ImageIcon(rutaImagenSeleccionada);

        Image imagenEscalada = imagen.getImage().getScaledInstance(
                100,
                120,
                Image.SCALE_SMOOTH
        );

        lblPreview.setIcon(new ImageIcon(imagenEscalada));
        lblPreview.setText("");

        txtLog.append("Imagen cargada: " + archivo.getName() + "\n");
    }

    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        if (estaCreada) {
        JOptionPane.showMessageDialog(this,
                "La pila ya está creada.",
                "Aviso",
                JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    pilaLibro = new PilaLibro();
    estaCreada = true;

    txtLog.append("Pila creada correctamente.\n");
    }//GEN-LAST:event_btnCrearActionPerformed

    private void btnPushActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPushActionPerformed

    if (!estaCreada) {
        JOptionPane.showMessageDialog(this,
                "Primero debes crear la pila.",
                "Pila no creada",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (!validarCampos()) {
        return;
    }

    try {
        double precio = obtenerPrecio();

        Libros libro = new Libros(
                txtIsbn.getText().trim(),
                txtTitulo.getText().trim(),
                txtAutor.getText().trim(),
                precio,
                rutaImagenSeleccionada
        );

        pilaLibro.apilar(libro);
        actualizarVistaPila();
        txtLog.append("Push: " + libro.getTitulo() + "\n");

        limpiarFormulario();

    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnPushActionPerformed

    private void btnPeekActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPeekActionPerformed

    if (!estaCreada) {
        JOptionPane.showMessageDialog(this,
                "Primero debes crear la pila.",
                "Pila no creada",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (pilaLibro.estaVacia()) {
        JOptionPane.showMessageDialog(this,
                "La pila está vacía.",
                "Peek",
                JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    try {
        Libros libro = pilaLibro.obtenerTope();

        JOptionPane.showMessageDialog(this,
                "Libro en el tope:\n\n"
                + "Título: " + libro.getTitulo() + "\n"
                + "Autor: " + libro.getAutor() + "\n"
                + "ISBN: " + libro.getIsbn() + "\n"
                + "Precio: $" + libro.getPrecio(),
                "Peek - Tope de la pila",
                JOptionPane.INFORMATION_MESSAGE);

        txtLog.append("Peek: " + libro.getTitulo() + "\n");

    } catch (IllegalStateException e) {
        JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnPeekActionPerformed

    private void btnPopActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPopActionPerformed

    if (!estaCreada) {
        JOptionPane.showMessageDialog(this,
                "Primero debes crear la pila.",
                "Pila no creada",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (pilaLibro.estaVacia()) {
        JOptionPane.showMessageDialog(this,
                "No se puede hacer Pop porque la pila está vacía.",
                "Pila vacía",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        Libros libro = pilaLibro.desapilar();
        actualizarVistaPila();

        JOptionPane.showMessageDialog(this,
                "Libro retirado:\n\n"
                + "Título: " + libro.getTitulo() + "\n"
                + "Autor: " + libro.getAutor() + "\n"
                + "ISBN: " + libro.getIsbn() + "\n"
                + "Precio: $" + libro.getPrecio(),
                "Pop",
                JOptionPane.INFORMATION_MESSAGE);

        txtLog.append("Pop: " + libro.getTitulo() + "\n");

    } catch (IllegalStateException e) {
        JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnPopActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
     if (!estaCreada) {
        JOptionPane.showMessageDialog(this,
                "Primero debes crear la pila.",
                "Pila no creada",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (pilaLibro.estaVacia()) {
        JOptionPane.showMessageDialog(this,
                "La pila ya está vacía.",
                "Limpiar",
                JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    pilaLibro.limpiar();
    actualizarVistaPila();

    limpiarFormulario();

    txtLog.append("Pila limpiada. Todos los elementos fueron eliminados.\n");

    JOptionPane.showMessageDialog(this,
            "La pila fue limpiada correctamente.",
            "Limpiar",
            JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_btnLimpiarActionPerformed

    private void btnDestruirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDestruirActionPerformed
     if (!estaCreada) {
        JOptionPane.showMessageDialog(this,
                "No existe una pila para destruir.",
                "Pila no creada",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    int respuesta = JOptionPane.showConfirmDialog(this,
            "¿Estás seguro de que deseas destruir la pila?",
            "Confirmar destrucción",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE);

    if (respuesta == JOptionPane.YES_OPTION) {

        pilaLibro = null;
        actualizarVistaPila();
        estaCreada = false;

        limpiarFormulario();

        txtLog.append("Pila destruida correctamente.\n");

        JOptionPane.showMessageDialog(this,
                "La pila fue destruida.",
                "Destruir Pila",
                JOptionPane.INFORMATION_MESSAGE);
    }

    }//GEN-LAST:event_btnDestruirActionPerformed

